/* ============================================================
 * 底层 I2C 写命令 / 写数据
 * ============================================================ */

/**
 * @brief  向 OLED 写命令
 * @param  cmd  命令字节
 */
static void OLED_WriteCmd(uint8_t cmd)
{
    uint8_t buf[2] = {0x00, cmd};   /* Co=0, D/C#=0 表示后续为命令 */
    HAL_I2C_Master_Transmit(&hi2c1, OLED_I2C_ADDR, buf, 2, 100);
}

/**
 * @brief  向 OLED 写数据
 * @param  data  数据字节
 */
static void OLED_WriteData(uint8_t data)
{
    uint8_t buf[2] = {0x40, data};  /* Co=0, D/C#=1 表示后续为数据 */
    HAL_I2C_Master_Transmit(&hi2c1, OLED_I2C_ADDR, buf, 2, 100);
}

/**
 * @brief  向 OLED 连续写多个数据字节
 * @param  data  数据指针
 * @param  len   数据长度
 */
static void OLED_WriteDataBurst(const uint8_t *data, uint16_t len)
{
    /* 使用 0x40 前缀表示数据，后续紧跟 len 字节数据 */
    uint8_t buf[129];  /* 单页最多 128 像素 */
    if (len > 128) len = 128;
    buf[0] = 0x40;
    memcpy(buf + 1, data, len);
    HAL_I2C_Master_Transmit(&hi2c1, OLED_I2C_ADDR, buf, len + 1, 200);
}

