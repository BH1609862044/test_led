/**
 * @brief  OLED 初始化（SSD1306 标准初始化序列）
 */
void OLED_Init(void)
{
    HAL_Delay(100);  /* 等待上电稳定 */

    OLED_WriteCmd(0xAE);  /* 关闭显示 */
    OLED_WriteCmd(0x20);  /* 设置内存地址模式 */
    OLED_WriteCmd(0x10);  /* 页地址模式（Page Addressing Mode） */
    OLED_WriteCmd(0xB0);  /* 设置页起始地址 0 */
    OLED_WriteCmd(0xC8);  /* COM 扫描方向：从下往上 */
    OLED_WriteCmd(0x00);  /* 设置低位列地址 */
    OLED_WriteCmd(0x10);  /* 设置高位列地址 */
    OLED_WriteCmd(0x40);  /* 设置起始行地址 */
    OLED_WriteCmd(0x81);  /* 设置对比度 */
    OLED_WriteCmd(0xFF);  /* 最大对比度 */
    OLED_WriteCmd(0xA1);  /* SEG 重映射：列 127 映射到 SEG0 */
    OLED_WriteCmd(0xA6);  /* 正常显示（非反色） */
    OLED_WriteCmd(0xA8);  /* 设置多路复用率 */
    OLED_WriteCmd(0x3F);  /* 1/64 duty */
    OLED_WriteCmd(0xA4);  /* 全局显示开启，遵循 GDDRAM 内容 */
    OLED_WriteCmd(0xD3);  /* 设置显示偏移 */
    OLED_WriteCmd(0x00);  /* 无偏移 */
    OLED_WriteCmd(0xD5);  /* 设置时钟分频 / 振荡频率 */
    OLED_WriteCmd(0xF0);  /* 高频 */
    OLED_WriteCmd(0xD9);  /* 设置预充电周期 */
    OLED_WriteCmd(0x22);  /* 预充电 2 时钟，放电 2 时钟 */
    OLED_WriteCmd(0xDA);  /* 设置 COM 引脚配置 */
    OLED_WriteCmd(0x12);  /* 可选 COM 左右重映射 */
    OLED_WriteCmd(0xDB);  /* 设置 VCOMH 电压 */
    OLED_WriteCmd(0x20);  /* 0.77*VCC */
    OLED_WriteCmd(0x8D);  /* 电荷泵设置 */
    OLED_WriteCmd(0x14);  /* 开启电荷泵 */
    OLED_WriteCmd(0xAF);  /* 开启显示 */

    OLED_Clear();
}

/**
 * @brief  设置光标位置
 * @param  page  页地址（0~7）
 * @param  col   列地址（0~127）
 */
void OLED_SetPos(uint8_t page, uint8_t col)
{
    OLED_WriteCmd(0xB0 + (page & 0x07));           /* 设置页地址 */
    OLED_WriteCmd(0x10 + ((col >> 4) & 0x0F));     /* 列地址高 4 位 */
    OLED_WriteCmd(0x00 + (col & 0x0F));            /* 列地址低 4 位 */
}

/**
 * @brief  清屏（逐页逐列写 0）
 */
void OLED_Clear(void)
{
    uint8_t page, col;
    for (page = 0; page < OLED_PAGES; page++) {
        OLED_SetPos(page, 0);
        for (col = 0; col < OLED_WIDTH; col++) {
            OLED_WriteData(0x00);
        }
    }
}

/**
 * @brief  在指定位置显示一个 6x8 ASCII 字符
 * @param  page  页地址（0~7）
 * @param  col   列地址（0~127，6 像素宽）
 * @param  ch    字符
 */
void OLED_ShowChar(uint8_t page, uint8_t col, char ch)
{
    uint8_t i;
    uint8_t index;

    if (ch < 32 || ch > 127) {
        ch = ' ';  /* 不可见字符显示为空格 */
    }
    index = ch - 32;

    OLED_SetPos(page, col);
    for (i = 0; i < 6; i++) {
        OLED_WriteData(oled_font6x8[index][i]);
    }
}

/**
 * @brief  在指定位置显示字符串
 * @param  page  页地址
 * @param  col   起始列地址
 * @param  str   字符串
 */
void OLED_ShowString(uint8_t page, uint8_t col, const char *str)
{
    while (*str && col < OLED_WIDTH) {
        OLED_ShowChar(page, col, *str);
        col += 6;   /* 每个字符 6 列 */
        str++;
    }
}

/**
 * @brief  显示数字（左对齐，不足长度前面补空格）
 * @param  page  页地址
 * @param  col   起始列地址
 * @param  num   数字值
 * @param  len   显示长度（字符数，最多 10 位）
 */
void OLED_ShowNum(uint8_t page, uint8_t col, uint32_t num, uint8_t len)
{
    char buf[11];
    uint8_t i;
    if (len > 10) len = 10;
    for (i = 0; i < len; i++) {
        buf[len - 1 - i] = '0' + (num % 10);
        num /= 10;
    }
    buf[len] = '\0';
    OLED_ShowString(page, col, buf);
}

